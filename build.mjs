// Puts Playload's engine, sound compiler and glyphs together with js/runtime.js -> out/playload.js,
// and writes the bundled game list -> out/games.json.   node build.mjs <playload repo> <out dir>
import fs from 'node:fs';
import path from 'node:path';
import { patchEngine } from './patches.mjs';

const [repo, out] = process.argv.slice(2);
const here = path.dirname(new URL(import.meta.url).pathname);
const read = (p) => fs.readFileSync(p, 'utf8');
fs.mkdirSync(out, { recursive: true });

const engineRaw = read(`${repo}/src/engine/engine.js`).replace(/^export /gm, '');
const soundAll = read(`${repo}/src/engine/sound.js`);
// only the score compiler; the AY chip is native (src/ay.c)
const sound = soundAll.slice(0, soundAll.indexOf('// Three square-wave channels')).replace(/^export /gm, '');
if (!sound.includes('function compileScore')) throw new Error('sound.js layout changed');

// glyphs: keep only what the engine reads
const glyphSrc = read(`${repo}/src/engine/glyphs.js`);
const glyphList = JSON.parse(glyphSrc.slice(glyphSrc.indexOf('['), glyphSrc.lastIndexOf(']') + 1).replace(/,\s*\]$/, ']'));
const glyphs =
  'const glyphs = ' +
  JSON.stringify(glyphList.map(({ ch, rows, ink, paper }) => ({ ch, rows, ink, paper }))) +
  ';';

const engine = patchEngine(engineRaw);

const sizeLine = 'const width = 160,\n    height = 144,\n    columns = 20,\n    lines = 18;';
if (!engine.includes(sizeLine)) throw new Error('engine.js layout changed');
const start = engine.indexOf('function createEngine');
const menuEngine = engine
  .slice(start)
  .replace('function createEngine', 'function createMenuEngine')
  .replace(sizeLine, 'const width = 320, height = 240, columns = 40, lines = 30;')
  .replace('MAX_SPRITES = 128', 'MAX_SPRITES = 1024');

let bundle = read(`${here}/js/runtime.js`)
  .replace('/*__ENGINE__*/', () => engine)
  .replace('/*__SOUND__*/', () => sound)
  .replace('/*__GLYPHS__*/', () => glyphs)
  .replace('/*__MENU_ENGINE__*/ null', () => menuEngine.trimEnd().replace(/;$/, ''));
fs.writeFileSync(`${out}/playload.js`, bundle);
// the same patched engine as a module, for test/fuzz.mjs
fs.mkdirSync(`${here}/build`, { recursive: true });
fs.writeFileSync(`${here}/build/engine-fast.mjs`, 'const hostRender = null, hostBind = null;\nconst Intl = globalThis.Intl;\n' + engine.replace('function createEngine', 'export function createEngine'));
fs.writeFileSync(`${out}/menu.js`, read(`${here}/js/menu.js`));
fs.writeFileSync(`${out}/dev.html`, read(`${here}/js/dev.html`));

// ---- Playload's 8x8 characters for the native list and the frame (letters, kana, symbols, emoji): everything that is one code point
{
  const table = new Map();
  for (const g of glyphList) {
    const key = g.ch.normalize('NFC').replace(/[\ufe0e\ufe0f]/g, '');
    const points = [...key];
    if (points.length === 1 && points[0].codePointAt(0) > 32) table.set(points[0].codePointAt(0), g.rows);
  }
  const sorted = [...table.entries()].sort((a, b) => a[0] - b[0]);
  fs.writeFileSync(
    `${here}/src/glyphs8.h`,
    `/* Generated by build.mjs from Playload's glyphs.js (fonts: Misaki Gothic, Unscii-8, Public Pixel; see licenses). */\n#pragma once\n#include <stdint.h>\n` +
      `#define G8_N ${sorted.length}\nstatic const uint32_t G8_CP[G8_N] = {${sorted.map((e) => e[0]).join(',')}};\n` +
      `static const uint8_t G8_ROWS[G8_N][8] = {${sorted.map((e) => '{' + e[1].join(',') + '}').join(',')}};\n`,
  );
}

// ---- games
const hashOf = (url) => url.slice(url.indexOf('#'));
const known = new Set(glyphList.map((g) => g.ch.normalize('NFC').replace(/[︎️]/g, '')));
const seg = new Intl.Segmenter('en', { granularity: 'grapheme' });
const drawable = (text) =>
  [...seg.segment(text)].every(({ segment }) => known.has(segment.normalize('NFC').replace(/[︎️]/g, '')));
// titles the 8x8 font can't write (kanji) get a plain-letter name
const plain = JSON.parse(read(`${here}/js/titles.json`));
const heavy = JSON.parse(read(`${here}/js/heavy.json`));
const heavyJit = JSON.parse(read(`${here}/js/heavy-jit.json`));
const games = [];
const pkg = JSON.parse(read(`${repo}/package.json`));

const examples = JSON.parse(read(`${repo}/data/examples.json`));
const { deflateRawSync } = await import('node:zlib');
const forEditor = [];
for (const ex of examples) {
  const source = read(`${repo}/examples/${ex.id}.js`);
  forEditor.push({ name: ex.name, note: ex.description, source });
  const hash = '#v1.' + deflateRawSync(Buffer.from(source, 'utf8'), { level: 9 }).toString('base64url');
  games.push({ tab: 1, title: ex.name, by: 'Takashi Kitao', note: ex.description, hash });
}
for (const game of JSON.parse(read(`${repo}/data/arcade.json`))) {
  let title = game.title;
  if (!drawable(title)) {
    if (!plain[title]) throw new Error('no plain title for ' + title);
    title = plain[title];
  }
  const handle = '@' + game.authorUrl.split('/').pop();
  games.push({ tab: 0, title, by: drawable(game.author) ? game.author : handle, note: game.publishedAt.slice(0, 10), hash: hashOf(game.url), heavy: heavy.includes(game.title) ? 1 : 0, heavyJit: heavyJit.includes(game.title) ? 1 : 0 });
}
fs.writeFileSync(`${out}/examples.json`, JSON.stringify(forEditor)); // the dev page's "Examples" menu
fs.writeFileSync(`${out}/games.json`, JSON.stringify({ version: pkg.version, plain, heavy, heavyJit, games }));
console.log(`playload ${pkg.version}: ${games.length} games, bundle ${bundle.length} bytes`);
